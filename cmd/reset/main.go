package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"

	"golang.org/x/tools/go/packages"
)

const (
	resetDirective = "generate:reset"
	genFileSuffix  = ".reset.gen.go"
)

// resetPackage holds the marked structs of one package, in source order.
type resetPackage struct {
	Pkg     *packages.Package
	Dir     string
	Structs []*types.TypeName
}

func main() {
	root := "."
	if len(os.Args) > 1 {
		root = os.Args[1]
	}

	if err := run(root); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(root string) error {
	pkgs, err := loadPackages(root)
	if err != nil {
		return err
	}

	// Marked structs from all packages: their Reset methods may not exist yet,
	// but fields of these types can still be reset with Reset.
	marked := make(map[*types.TypeName]bool)
	var found []*resetPackage
	for _, pkg := range pkgs {
		rp := findResetStructs(pkg)
		if rp == nil {
			continue
		}
		for _, obj := range rp.Structs {
			marked[obj] = true
		}
		found = append(found, rp)
	}

	for _, rp := range found {
		path, err := writeResetFile(rp, marked)
		if err != nil {
			return err
		}
		fmt.Printf("%s: %d Reset method(s)\n", path, len(rp.Structs))
	}

	return nil
}

// loadPackages loads all packages under root with syntax and type information.
//
// Load errors are only printed as warnings: the generator needs just the
// struct declarations, and errors in previously generated files go away once
// those files are rewritten. Fields whose types could not be resolved make the
// generation fail later.
func loadPackages(root string) ([]*packages.Package, error) {
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax |
			packages.NeedTypes | packages.NeedTypesInfo,
		Dir: root,
	}

	pkgs, err := packages.Load(cfg, "./...")
	if err != nil {
		return nil, err
	}

	var loaded []*packages.Package
	for _, pkg := range pkgs {
		for _, e := range pkg.Errors {
			if !strings.Contains(e.Pos+e.Msg, genFileSuffix) {
				fmt.Fprintf(os.Stderr, "warning: %s: %v\n", pkg.PkgPath, e)
			}
		}

		if pkg.Types == nil || pkg.TypesInfo == nil {
			continue
		}
		loaded = append(loaded, pkg)
	}

	return loaded, nil
}

// findResetStructs returns the structs of the package marked with a
// "// generate:reset" comment, or nil if there are none.
func findResetStructs(pkg *packages.Package) *resetPackage {
	var structs []*types.TypeName
	var dir string

	for _, file := range pkg.Syntax {
		for _, spec := range resetSpecs(file) {
			obj, ok := pkg.TypesInfo.Defs[spec.Name].(*types.TypeName)
			if !ok {
				continue
			}
			structs = append(structs, obj)
			dir = filepath.Dir(pkg.Fset.Position(spec.Pos()).Filename)
		}
	}

	if len(structs) == 0 {
		return nil
	}

	return &resetPackage{Pkg: pkg, Dir: dir, Structs: structs}
}

func resetSpecs(f *ast.File) []*ast.TypeSpec {
	var specs []*ast.TypeSpec

	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}

		for _, spec := range gd.Specs {
			ts := spec.(*ast.TypeSpec)
			if _, ok := ts.Type.(*ast.StructType); !ok {
				continue
			}

			doc := ts.Doc
			if doc == nil && !gd.Lparen.IsValid() {
				doc = gd.Doc
			}
			if hasDirective(doc) {
				specs = append(specs, ts)
			}
		}
	}

	return specs
}

func hasDirective(doc *ast.CommentGroup) bool {
	if doc == nil {
		return false
	}

	for _, c := range doc.List {
		if strings.TrimSpace(strings.TrimPrefix(c.Text, "//")) == resetDirective {
			return true
		}
	}
	return false
}

// writeResetFile writes {package}.reset.gen.go with a Reset method for every
// struct of the package and returns the file path.
func writeResetFile(rp *resetPackage, marked map[*types.TypeName]bool) (string, error) {
	g := &generator{
		pkg:       rp.Pkg.Types,
		marked:    marked,
		preferred: sourceImportNames(rp.Pkg),
		imports:   make(map[string]importSpec),
		names:     make(map[string]bool),
	}
	for _, obj := range rp.Structs {
		g.writeMethod(obj)
	}
	if g.err != nil {
		return "", g.err
	}

	var src bytes.Buffer
	fmt.Fprintf(&src, "// Code generated by cmd/reset; DO NOT EDIT.\n\npackage %s\n", rp.Pkg.Name)
	g.writeImports(&src)
	src.Write(g.body.Bytes())

	formatted, err := format.Source(src.Bytes())
	if err != nil {
		return "", fmt.Errorf("format generated code for %s: %w", rp.Dir, err)
	}

	path := filepath.Join(rp.Dir, rp.Pkg.Name+genFileSuffix)
	if err := os.WriteFile(path, formatted, 0644); err != nil {
		return "", err
	}

	return path, nil
}

type importSpec struct {
	name  string
	alias bool
}

// generator writes the Reset methods of one package.
type generator struct {
	pkg       *types.Package
	marked    map[*types.TypeName]bool
	preferred map[string]string     // Import names used in the package sources, by path.
	imports   map[string]importSpec // By import path.
	names     map[string]bool       // Import names in use.
	body      bytes.Buffer
	err       error
}

// sourceImportNames returns the names under which the package sources import
// other packages, so the generated code reads like the code it was made from.
func sourceImportNames(pkg *packages.Package) map[string]string {
	declared := make(map[string]string)
	for _, imp := range pkg.Types.Imports() {
		declared[imp.Path()] = imp.Name()
	}

	names := make(map[string]string)
	for _, file := range pkg.Syntax {
		for _, spec := range file.Imports {
			path, err := strconv.Unquote(spec.Path.Value)
			if err != nil {
				continue
			}

			name := declared[path]
			if spec.Name != nil {
				name = spec.Name.Name
			}
			if name == "" || name == "_" || name == "." {
				continue
			}
			if _, ok := names[path]; !ok {
				names[path] = name
			}
		}
	}

	return names
}

// writeImports writes the standard library imports first and then the others,
// in the groups goimports uses.
func (g *generator) writeImports(w *bytes.Buffer) {
	if len(g.imports) == 0 {
		return
	}

	var std, other []string
	for path := range g.imports {
		if isStdlib(path) {
			std = append(std, path)
		} else {
			other = append(other, path)
		}
	}
	slices.Sort(std)
	slices.Sort(other)

	w.WriteString("\nimport (\n")
	for i, group := range [][]string{std, other} {
		if i > 0 && len(std) > 0 && len(other) > 0 {
			w.WriteString("\n")
		}
		for _, path := range group {
			if spec := g.imports[path]; spec.alias {
				fmt.Fprintf(w, "%s %q\n", spec.name, path)
			} else {
				fmt.Fprintf(w, "%q\n", path)
			}
		}
	}
	w.WriteString(")\n")
}

// isStdlib reports whether path is a standard library package: those have no
// dot in the first path element.
func isStdlib(path string) bool {
	first, _, _ := strings.Cut(path, "/")
	return !strings.Contains(first, ".")
}

// qualifier names types of other packages in the generated code and records
// their imports. It uses the import name from the package sources when there is
// one; names that are already taken get a number.
func (g *generator) qualifier(p *types.Package) string {
	if p == g.pkg {
		return ""
	}
	if spec, ok := g.imports[p.Path()]; ok {
		return spec.name
	}

	base := p.Name()
	if name, ok := g.preferred[p.Path()]; ok {
		base = name
	}

	name := base
	for i := 2; g.names[name]; i++ {
		name = fmt.Sprintf("%s%d", base, i)
	}
	g.names[name] = true
	g.imports[p.Path()] = importSpec{name: name, alias: name != p.Name()}

	return name
}

func (g *generator) writeMethod(obj *types.TypeName) {
	named := obj.Type().(*types.Named)
	st := named.Underlying().(*types.Struct)
	recv := receiverName(obj.Name(), g.reservedNames(named))

	fmt.Fprintf(&g.body, "\n// Reset resets the fields of %s so it can be reused.\n", obj.Name())
	fmt.Fprintf(&g.body, "func (%s *%s) Reset() {\n", recv, receiverType(named))
	fmt.Fprintf(&g.body, "if %s == nil {\nreturn\n}\n", recv)

	separated := false
	for i := range st.NumFields() {
		f := st.Field(i)
		if f.Name() == "_" {
			continue
		}
		if !validType(f.Type()) {
			g.err = errors.Join(g.err, fmt.Errorf("%s.%s: cannot resolve the field type, fix the build errors above",
				obj.Name(), f.Name()))
			continue
		}
		if !separated {
			g.body.WriteString("\n")
			separated = true
		}
		g.resetValue(recv+"."+f.Name(), f.Type())
	}

	g.body.WriteString("}\n")
}

// resetValue writes the statements that reset the value of expr of type t.
func (g *generator) resetValue(expr string, t types.Type) {
	if _, ok := t.(*types.TypeParam); ok {
		fmt.Fprintf(&g.body, "%s = *new(%s)\n", expr, g.typeString(t))
		return
	}

	switch u := t.Underlying().(type) {
	case *types.Pointer:
		fmt.Fprintf(&g.body, "if %s != nil {\n", expr)
		if g.hasReset(u.Elem()) {
			fmt.Fprintf(&g.body, "%s.Reset()\n", expr)
		} else {
			g.resetValue("*"+expr, u.Elem())
		}
		g.body.WriteString("}\n")
		return
	case *types.Interface, *types.Signature, *types.Chan:
		fmt.Fprintf(&g.body, "%s = nil\n", expr)
		return
	}

	if g.hasReset(t) {
		fmt.Fprintf(&g.body, "%s.Reset()\n", operand(expr))
		return
	}

	switch u := t.Underlying().(type) {
	case *types.Basic:
		fmt.Fprintf(&g.body, "%s = %s\n", expr, zeroBasic(u))
	case *types.Slice:
		fmt.Fprintf(&g.body, "%s = %s[:0]\n", expr, operand(expr))
	case *types.Map:
		fmt.Fprintf(&g.body, "clear(%s)\n", expr)
	default: // A struct without Reset or an array.
		fmt.Fprintf(&g.body, "%s = %s{}\n", expr, g.typeString(t))
	}
}

// hasReset reports whether t has a Reset() method, or will get one because
// it is a marked struct.
func (g *generator) hasReset(t types.Type) bool {
	if n, ok := t.(*types.Named); ok && g.marked[n.Origin().Obj()] {
		return true
	}

	obj, _, _ := types.LookupFieldOrMethod(t, true, g.pkg, "Reset")
	fn, ok := obj.(*types.Func)
	if !ok {
		return false
	}

	sig := fn.Type().(*types.Signature)
	return sig.Params().Len() == 0 && sig.Results().Len() == 0
}

// validType reports whether t and all types it is built from were resolved.
func validType(t types.Type) bool {
	switch t := t.(type) {
	case *types.Basic:
		return t.Kind() != types.Invalid
	case *types.Pointer:
		return validType(t.Elem())
	case *types.Slice:
		return validType(t.Elem())
	case *types.Array:
		return validType(t.Elem())
	case *types.Map:
		return validType(t.Key()) && validType(t.Elem())
	case *types.Chan:
		return validType(t.Elem())
	default:
		return true
	}
}

func (g *generator) typeString(t types.Type) string {
	return types.TypeString(t, g.qualifier)
}

// operand wraps a dereference in parentheses, so it can be sliced or have a
// method called: (*p)[:0], (*p).Reset().
func operand(expr string) string {
	if strings.HasPrefix(expr, "*") {
		return "(" + expr + ")"
	}
	return expr
}

func zeroBasic(b *types.Basic) string {
	switch info := b.Info(); {
	case info&types.IsBoolean != 0:
		return "false"
	case info&types.IsString != 0:
		return `""`
	case info&types.IsNumeric != 0:
		return "0"
	default: // unsafe.Pointer
		return "nil"
	}
}

// reservedNames returns the names a receiver of named must not shadow: they
// may be used in the method body.
func (g *generator) reservedNames(named *types.Named) map[string]bool {
	reserved := make(map[string]bool)
	for _, name := range g.pkg.Scope().Names() {
		reserved[name] = true
	}
	for _, imp := range g.pkg.Imports() {
		reserved[imp.Name()] = true
	}
	for _, name := range g.preferred {
		reserved[name] = true
	}
	for name := range g.names {
		reserved[name] = true
	}
	for i := range named.TypeParams().Len() {
		reserved[named.TypeParams().At(i).Obj().Name()] = true
	}

	return reserved
}

// receiverName returns the lowercased capital letters of the type name, like
// "rs" for ResetableStruct. If that name is a keyword or reserved, it falls
// back to the first letter and then to "recv".
func receiverName(typeName string, reserved map[string]bool) string {
	var initials []rune
	for _, r := range typeName {
		if unicode.IsUpper(r) {
			initials = append(initials, unicode.ToLower(r))
		}
	}
	first, _ := utf8.DecodeRuneInString(typeName)

	candidates := []string{string(initials), string(unicode.ToLower(first)), "recv"}
	for _, name := range candidates {
		if name != "" && !token.IsKeyword(name) && !reserved[name] {
			return name
		}
	}

	name := "recv"
	for i := 2; reserved[name]; i++ {
		name = fmt.Sprintf("recv%d", i)
	}
	return name
}

// receiverType returns the type name with its type parameters, like
// "Pair[K, V]" for type Pair[K comparable, V any] struct{...}.
func receiverType(named *types.Named) string {
	tparams := named.TypeParams()
	if tparams.Len() == 0 {
		return named.Obj().Name()
	}

	params := make([]string, 0, tparams.Len())
	for i := range tparams.Len() {
		params = append(params, tparams.At(i).Obj().Name())
	}

	return named.Obj().Name() + "[" + strings.Join(params, ", ") + "]"
}
